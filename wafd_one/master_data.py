def _default_company() -> str | None:
    if not frappe.db.exists("DocType", "Company"):
        return None
    company = frappe.defaults.get_global_default("company")
    if company and frappe.db.exists("Company", company):
        return company
    return frappe.db.get_value("Company", {}, "name", order_by="creation asc")


def _ensure_uom(name: str, must_be_whole_number: int = 0) -> bool:
    if frappe.db.exists("UOM", name):
        return False
    _insert("UOM", {"uom_name": name, "must_be_whole_number": must_be_whole_number})
    return True


def _ensure_item_group(name: str) -> bool:
    if frappe.db.exists("Item Group", name):
        return False
    parent = "All Item Groups" if frappe.db.exists("Item Group", "All Item Groups") else None
    values = {"item_group_name": name, "is_group": 0}
    if parent:
        values["parent_item_group"] = parent
    _insert("Item Group", values)
    return True


def _erp_warehouse_name(warehouse_name: str, company: str) -> str | None:
    return frappe.db.get_value("Warehouse", {"warehouse_name": warehouse_name, "company": company}, "name")


def _ensure_erp_warehouse(warehouse_name: str, company: str) -> bool:
    if _erp_warehouse_name(warehouse_name, company):
        return False
    abbr = frappe.db.get_value("Company", company, "abbr")
    root_name = f"WAFD Warehouses - {abbr}" if abbr else "WAFD Warehouses"
    root = frappe.db.get_value("Warehouse", {"warehouse_name": "WAFD Warehouses", "company": company}, "name")
    if not root:
        doc = _insert("Warehouse", {
            "warehouse_name": "WAFD Warehouses",
            "company": company,
            "is_group": 1,
        })
        root = doc.name
    _insert("Warehouse", {
        "warehouse_name": warehouse_name,
        "company": company,
        "parent_warehouse": root,
        "is_group": 0,
    })
    return True


def install_erpnext_inventory_masters() -> dict[str, int]:
    """Create missing ERPNext Item/UOM/Item Group/Warehouse masters safely.

    No stock quantity is fabricated. Zero WAFD balance rows are created only as
    explicit placeholders until an approved opening count or stock movement is posted.
    """
    result = {
        "erp_uoms": 0,
        "erp_item_groups": 0,
        "erp_items": 0,
        "erp_warehouses": 0,
        "stock_balance_placeholders": 0,
    }
    required = ("UOM", "Item Group", "Item", "Warehouse", "Company")
    if not all(frappe.db.exists("DocType", dt) for dt in required):
        return result

    for source, erp_uom in UOM_MAP.items():
        whole = 1 if erp_uom in {"Nos", "Carton", "Box"} else 0
        result["erp_uoms"] += int(_ensure_uom(erp_uom, whole))

    for group in sorted(set(ITEM_GROUP_MAP.values())):
        result["erp_item_groups"] += int(_ensure_item_group(group))

    company = _default_company()
    if company:
        for warehouse_name, _warehouse_type, _location in WAREHOUSES:
            result["erp_warehouses"] += int(_ensure_erp_warehouse(warehouse_name, company))

    for name, code, category, source_uom, cost, minimum, _supplier in INGREDIENTS:
        erp_uom = UOM_MAP.get(source_uom, "Nos")
        item_group = ITEM_GROUP_MAP.get(category, "WAFD Other Materials")
        if not frappe.db.exists("Item", code):
            _insert("Item", {
                "item_code": code,
                "item_name": name,
                "description": f"{name} - WAFD ONE inventory master",
                "item_group": item_group,
                "stock_uom": erp_uom,
                "is_stock_item": 1,
                "include_item_in_manufacturing": 1,
                "standard_rate": cost,
                "disabled": 0,
            })
            result["erp_items"] += 1

        preferred_warehouse = CATEGORY_WAREHOUSE_MAP.get(category, WAREHOUSES[0][0])
        if frappe.db.exists("WAFD Warehouse", preferred_warehouse) and not frappe.db.exists(
            "WAFD Stock Balance", {"warehouse": preferred_warehouse, "ingredient": name}
        ):
            _insert("WAFD Stock Balance", {
                "warehouse": preferred_warehouse,
                "ingredient": name,
                "uom": source_uom,
                "actual_quantity": 0,
                "reserved_quantity": 0,
                "available_quantity": 0,
                "average_cost": cost,
                "stock_value": 0,
                "count_status": "غير مجرود / Not Counted",
                "stock_source_note": "Placeholder created by WAFD master-data installer. Enter approved opening stock through a stock movement or physical count.",
            })
            result["stock_balance_placeholders"] += 1

    return result

def load_reference_master_data() -> dict[str, int]:
    """Create missing WAFD reference data without touching existing records."""
    counts = {"missions": 0, "hotels": 0, "suppliers": 0, "ingredients": 0, "warehouses": 0, "recipes": 0, "stock_balances": 0,
              "erp_uoms": 0, "erp_item_groups": 0, "erp_items": 0, "erp_warehouses": 0,
              "stock_balance_placeholders": 0}

    for name, country in MISSIONS:
        if not _exists("WAFD Mission", "mission_name", name):
            _insert("WAFD Mission", {"mission_name": name, "country": country, "address": "مكتب شؤون الحجاج - المدينة المنورة", "status": ACTIVE})
            counts["missions"] += 1

    for name, district, address, lat, lon in HOTELS:
        existing = _exists("WAFD Hotel", "hotel_name", name)
        values = {"hotel_name": name, "city": "المدينة المنورة", "district": district, "address": address, "status": ACTIVE}
        if lat is not None:
            values["latitude"] = lat
        if lon is not None:
            values["longitude"] = lon
        if not existing:
            _insert("WAFD Hotel", values)
            counts["hotels"] += 1
        else:
            # Fill only missing reference fields; never overwrite user-entered values.
            doc = frappe.get_doc("WAFD Hotel", existing)
            changed = False
            for field in ("city", "district", "address", "latitude", "longitude"):
                value = values.get(field)
                if value not in (None, "") and not doc.get(field):
                    doc.set(field, value)
                    changed = True
            if changed:
                doc.flags.ignore_permissions = True
                doc.flags.ignore_version = True
                doc.save(ignore_permissions=True)

    for name, category in SUPPLIERS:
        if not _exists("WAFD Supplier", "supplier_name", name):
            _insert("WAFD Supplier", {"supplier_name": name, "category": category, "address": "المدينة المنورة", "payment_terms": "حسب العقد وأمر الشراء", "status": ACTIVE})
            counts["suppliers"] += 1

    for name, code, category, uom, cost, minimum, supplier in INGREDIENTS:
        if not _exists("WAFD Ingredient", "ingredient_name", name):
            _insert("WAFD Ingredient", {"ingredient_name": name, "item_code": code, "category": category, "uom": uom, "standard_cost": cost, "minimum_stock": minimum, "default_supplier": supplier, "status": ACTIVE})
            counts["ingredients"] += 1

    for name, warehouse_type, location in WAREHOUSES:
        if not _exists("WAFD Warehouse", "warehouse_name", name):
            _insert("WAFD Warehouse", {"warehouse_name": name, "warehouse_type": warehouse_type, "location": location, "status": ACTIVE})
            counts["warehouses"] += 1

    recipe_specs = [(name, category, "عام / General", "جميع البعثات", items) for name, category, items in RECIPES]
    recipe_specs.extend(NATIONALITY_RECIPES)
    recipe_specs.extend(ADDITIONAL_RECIPES)
    for recipe_name, category, cuisine, nationalities, items in recipe_specs:
        existing = _exists("WAFD Recipe", "recipe_name", recipe_name)
        if existing:
            recipe = frappe.get_doc("WAFD Recipe", existing)
            changed = False
            if recipe.meta.has_field("cuisine") and not recipe.cuisine:
                recipe.cuisine = cuisine; changed = True
            if recipe.meta.has_field("suitable_nationalities") and not recipe.suitable_nationalities:
                recipe.suitable_nationalities = nationalities; changed = True
            if changed:
                recipe.save(ignore_permissions=True)
            continue
        recipe_values = {
            "doctype": "WAFD Recipe", "recipe_name": recipe_name, "meal_category": category,
            "yield_quantity": 100, "status": RECIPE_ACTIVE, "cuisine": cuisine,
            "instructions": "وصفة تشغيلية معيارية لعدد 100 حصة. يجب اعتماد الكميات والطعم ومستوى التوابل مع ممثل البعثة قبل الإنتاج.",
            "verification_status": "تشغيلي داخلي / Internal Operational",
            "source_notes": "مرجع تشغيلي داخلي قابل للتعديل حسب اشتراطات البعثة والعقد.",
            "items": [],
        }
        recipe = frappe.get_doc(recipe_values)
        if recipe.meta.has_field("suitable_nationalities"):
            recipe.suitable_nationalities = nationalities
        if recipe.meta.has_field("mission_menu_notes"):
            recipe.mission_menu_notes = "تُراجع الحساسية الغذائية، مستوى التوابل، ونمط التقديم مع ممثل البعثة قبل الاعتماد."
        missing_items = []
        for ingredient, quantity in items:
            if frappe.db.exists("WAFD Ingredient", ingredient):
                recipe.append("items", {"ingredient": ingredient, "quantity": quantity})
            else:
                missing_items.append(ingredient)
        if missing_items:
            frappe.log_error("Missing recipe ingredients: " + ", ".join(missing_items), "WAFD RC13 Master Data")
        recipe.flags.ignore_permissions = True
        recipe.flags.ignore_version = True
        recipe.insert(ignore_permissions=True)
        counts["recipes"] += 1

    erp_counts = install_erpnext_inventory_masters()
    counts.update({key: counts.get(key, 0) + value for key, value in erp_counts.items()})

    # Packaging catalogue and reusable profiles.
    if frappe.db.exists("DocType", "WAFD Packaging Material"):
        for name, code, category, cost, units in PACKAGING_MATERIALS:
            if not frappe.db.exists("WAFD Packaging Material", code):
                _insert("WAFD Packaging Material", {"material_code": code, "material_name": name, "category": category, "unit_cost": cost, "units_per_pack": units, "warehouse": "مستودع التغليف", "is_active": 1})
    if frappe.db.exists("DocType", "WAFD Packaging Profile"):
        for name, meal_type, service_type, units_per_box, rows in PACKAGING_PROFILES:
            if frappe.db.exists("WAFD Packaging Profile", name):
                continue
            doc = frappe.get_doc({"doctype":"WAFD Packaging Profile", "profile_name":name, "meal_type":meal_type, "service_type":service_type, "units_per_box":units_per_box, "label_template":"المشروع: {project} | الدفعة: {batch} | الكمية: {quantity}", "is_active":1})
            for code, qty in rows:
                if frappe.db.exists("WAFD Packaging Material", code):
                    doc.append("materials", {"packaging_material":code, "quantity_per_meal":qty})
            doc.insert(ignore_permissions=True)

    # Inventory quantities are operational facts and are never fabricated.
    # The installer creates Item masters and zero placeholders only. Opening
    # quantities must come from an approved physical count or stock movement.
    return counts
