import frappe

ZONES = [('1', 'الإقليمية', 'الساحات الشمالية الغربية – قسم النساء الغربي'), ('2', 'إعاشة المدينة', 'التوسعة الشمالية'), ('3', 'سدرة العالمية', 'الساحات الغربية الجديدة'), ('4', 'بهار حار', 'التوسعة الشرقية'), ('5', 'مرمرة شلال', 'الحصوات'), ('6', 'مصنع صحاري', 'الساحات الغربية الجديدة'), ('7', 'القدوة الذكية', 'التوسعة الغربية'), ('8', 'الوطنية الرائدة', 'الساحات الغربية الجديدة'), ('9', 'رمك', 'جزئي الساحات الغربية الداخلية - جزئي الساحات الغربية الجديدة'), ('10', 'رؤى طيبة', 'السطح الشمالي'), ('11', 'إطعام', 'قسم النساء الشرقي'), ('12', 'بندر خميري', 'الساحات الشمالية الشرقية'), ('13', 'السرايا الفضية', 'الحرم القديم - ساحة البقيع'), ('14', 'أحد طيبة', 'الساحات الغربية الداخلية'), ('15', 'صفوة السلام', 'السطح الغربي'), ('16', 'صفوة أبرار طيبة', 'ساحة السلام - الساحات الجنوبية'), ('17', 'ضيوف المدينة', 'السطح الشرقي'), ('18', 'رؤيا الأندلس', 'الساحات الغربية الجديدة'), ('19', 'أقران اليوم', 'المداخل الغربية والجنوبية (توزيع يدوي)'), ('20', 'صفوة طيبة', 'المداخل الشمالية والشرقية (توزيع يدوي)')]

def execute():
    for code, company, location in ZONES:
        name = frappe.db.get_value("WAFD Iftar Haram Zone", {"zone_code": code}, "name")
        if name:
            doc = frappe.get_doc("WAFD Iftar Haram Zone", name)
            doc.company_name = company
            doc.location_name = location
            doc.active = 1
            doc.save(ignore_permissions=True)
        else:
            frappe.get_doc({"doctype":"WAFD Iftar Haram Zone","zone_code":code,"company_name":company,"location_name":location,"active":1}).insert(ignore_permissions=True)
